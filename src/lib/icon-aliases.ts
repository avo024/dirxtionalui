const CONCEPT_SET: ReadonlySet<string> = new Set(ICON_CONCEPTS);

/** Resolve a concept id or legacy Lucide name to a concept id, or null if unknown. */
export function resolveIconId(name: string | null | undefined): IconConceptId | null {
  if (!name) return null;
  if (CONCEPT_SET.has(name)) return name as IconConceptId;
  return (ICON_ALIASES as Record<string, IconConceptId>)[name] ?? null;
}
